import '../domain/models.dart';

class ImportedChatCompletionPreset {
  const ImportedChatCompletionPreset({
    required this.name,
    required this.prompts,
    this.temperature,
    this.topP,
    this.frequencyPenalty,
    this.presencePenalty,
    this.maxOutputTokens,
    this.stopSequences = const [],
  });

  final String name;
  final PromptConfig prompts;
  final double? temperature;
  final double? topP;
  final double? frequencyPenalty;
  final double? presencePenalty;
  final int? maxOutputTokens;
  final List<String> stopSequences;
}

/// Maps the declarative parts of a SillyTavern Chat Completion preset.
///
/// Prompt Manager markers such as chatHistory, charDescription and worldInfo
/// are generated by this app, so they are not copied as duplicate text. Named
/// editable prompts (main, auxiliary and post-history) are preserved.
class ChatCompletionPresetCodec {
  const ChatCompletionPresetCodec();

  bool matches(Map<String, dynamic> json) =>
      json['prompts'] is List &&
      (json.containsKey('chat_completion_source') ||
          json.containsKey('temperature') ||
          json.containsKey('openai_max_tokens'));

  ImportedChatCompletionPreset decode(
    Map<String, dynamic> json, {
    List<RegexRule> existingRules = const [],
  }) {
    final mainPrompt = <String>[];
    final auxiliaryPrompt = <String>[];
    var postHistory = '';
    for (final value in json['prompts'] as List) {
      if (value is! Map) continue;
      final item = Map<String, dynamic>.from(value);
      final identifier = _text(item['identifier']);
      final name = _text(item['name']);
      final content = _text(item['content']);
      if (content.isEmpty || item['marker'] == true) continue;
      if (identifier == 'main' || name.toLowerCase() == 'main prompt') {
        mainPrompt.add(content);
      } else if (identifier == 'nsfw' ||
          name.toLowerCase() == 'auxiliary prompt') {
        auxiliaryPrompt.add(content);
      } else if (identifier == 'jailbreak' ||
          name.toLowerCase() == 'post-history instructions') {
        postHistory = content;
      }
    }
    final systemParts = <String>[
      ...mainPrompt,
      if (auxiliaryPrompt.isNotEmpty)
        '【辅助提示词】\n${auxiliaryPrompt.join('\n\n')}',
    ];
    final stop = json['stop'];
    final stops = stop is List
        ? stop
              .whereType<String>()
              .map((value) => value.trim())
              .where((value) => value.isNotEmpty)
              .take(4)
              .toList()
        : const <String>[];
    return ImportedChatCompletionPreset(
      name: _text(json['name']).isEmpty
          ? '导入的 Chat Completion 预设'
          : _text(json['name']),
      prompts: PromptConfig(
        systemPrefix: systemParts.join('\n\n'),
        postHistoryInstructions: postHistory,
        rules: [...existingRules],
      ),
      temperature: _double(json['temperature'], 0, 2),
      topP: _double(json['top_p'], 0, 1),
      frequencyPenalty: _double(json['frequency_penalty'], -2, 2),
      presencePenalty: _double(json['presence_penalty'], -2, 2),
      maxOutputTokens: switch (json['openai_max_tokens']) {
        final num value when value.toInt() > 0 => value.toInt().clamp(
          1,
          131072,
        ),
        _ => null,
      },
      stopSequences: stops,
    );
  }

  String _text(Object? value) =>
      value is String ? value.trim() : value?.toString() ?? '';

  double? _double(Object? value, double min, double max) {
    final number = value is num ? value.toDouble() : null;
    if (number == null || !number.isFinite) return null;
    return number.clamp(min, max);
  }
}
